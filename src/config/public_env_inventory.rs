//! DOC-03 public `FERRUM_*` settings inventory (docs ↔ ferrum.conf).
//!
//! [`PUBLIC_FERRUM_ENV_SETTINGS`] is the complete, sorted, machine-readable
//! inventory of public operator `FERRUM_*` controls. It includes:
//! - settings accepted by production `EnvConfig` parsing
//!   (`env_config!` keys, TLS `*_SOURCE` overrides, `FERRUM_MODE`, and
//!   free helpers such as `tls_managed_store_path_from_env`)
//! - public controls resolved outside `EnvConfig` (conf-file bootstrap,
//!   secret-fetch timeout, mesh/injector/node-agent/pool helpers, PKCS#11,
//!   and dynamically constructed injector resource quantities)
//!
//! [`PUBLIC_FERRUM_ENV_COVERAGE_EXEMPTIONS`] is a small allowlist for accepted
//! compatibility aliases that intentionally share the canonical setting's
//! docs/template row. Build-out policy does not add new legacy shims; only
//! existing permitted aliases belong here.
//!
//! External unit tests under `tests/unit/config/env_docs_parity_tests.rs`
//! fail closed when a public inventory setting lacks a
//! `docs/configuration.md` table row or a `ferrum.conf` template assignment,
//! and when production `EnvConfig` acceptance sites omit a key from this
//! inventory.

